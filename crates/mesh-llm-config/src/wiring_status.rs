//! Exhaustive schema-to-status manifest for every canonical `config.toml`
//! path in scope for issue #1462.
//!
//! This manifest is the single source of truth PR 1 of the #1462 stack
//! derives static validation from: for every canonical TOML path it records
//! whether that path is [`WiringStatus::Wired`], [`WiringStatus::Partial`],
//! [`WiringStatus::Unwired`], or [`WiringStatus::Rejected`] today, which
//! implementation PR in #1462 (if any) completes the runtime path, why, and
//! what a downstream validator should do about it
//! ([`WiringBehavior`]).
//!
//! `crates/mesh-llm-config/src/website_docs_parity.rs` asserts that this
//! manifest agrees, path for path, with the `Status` column of
//! `website/src/docs/pages/config-reference.md` and the `Wiring status`
//! column of `docs/skippy/CONFIGURATION.md`. `crates/mesh-llm-config/src/wiring_validation.rs`
//! derives `ConfigDiagnostic`s from [`WiringBehavior`] so `mesh-llm config
//! validate` agrees with real runtime support instead of drifting from it.

mod checkpoint;
mod topology;

/// The wiring status of one canonical config path, matching the `Status`
/// column used across the public docs (`website/src/docs/pages/config-reference.md`)
/// and the internal matrix (`docs/skippy/CONFIGURATION.md`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WiringStatus {
    Wired,
    Partial,
    Unwired,
    Rejected,
}

impl WiringStatus {
    /// Render the lowercase token used by both status-matrix documents.
    pub const fn as_matrix_token(self) -> &'static str {
        match self {
            Self::Wired => "wired",
            Self::Partial => "partial",
            Self::Unwired => "unwired",
            Self::Rejected => "rejected",
        }
    }
}

/// What a static validator should do about a path's current wiring gap.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WiringBehavior {
    /// The field is fully wired (or its validator behavior is owned
    /// elsewhere already); `mesh-llm config validate` emits no manifest-
    /// driven diagnostic for it.
    None,
    /// The field is explicitly rejected; belongs to another subsystem or
    /// is not implemented at all. Emits a `RejectedField` error.
    Rejected,
    /// The field passes static validation today but currently causes a
    /// hard failure downstream (at model load or request resolution).
    /// `mesh-llm config validate` should surface this as an error instead
    /// of letting the operator discover it at resolve time.
    BailsDownstream,
    /// The field passes static validation and resolution, but no runtime
    /// consumer reads the resolved value: it is a silent no-op today.
    /// `mesh-llm config validate` should warn.
    SilentNoOp,
}

/// One row of the exhaustive schema-to-status manifest.
#[derive(Clone, Copy, Debug)]
pub struct WiringEntry {
    /// The canonical, unprefixed key path (e.g. `model_fit.kv_offload`),
    /// matching the short form the website configuration reference and the
    /// internal status matrix both document once per field.
    pub path: &'static str,
    pub status: WiringStatus,
    /// The #1462 implementation PR that completes this field's runtime
    /// path, or `"n/a"` for fields with no owning PR in this stack (fully
    /// wired fields, and permanently rejected fields).
    pub owner: &'static str,
    /// Why the field has this status today; empty for `Wired` fields.
    pub reason: &'static str,
    pub behavior: WiringBehavior,
}

