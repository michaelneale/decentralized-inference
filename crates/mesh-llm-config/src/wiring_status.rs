/// Look up a manifest entry by its canonical short path.
pub fn wiring_entry_for_path(path: &str) -> Option<&'static WiringEntry> {
    WIRING_MANIFEST.iter().find(|entry| entry.path == path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    #[test]
    fn manifest_has_no_duplicate_paths() {
        let mut counts: BTreeMap<&str, u32> = BTreeMap::new();
        for entry in WIRING_MANIFEST {
            *counts.entry(entry.path).or_insert(0) += 1;
        }
        let duplicates: Vec<_> = counts.iter().filter(|(_, count)| **count > 1).collect();
        assert!(
            duplicates.is_empty(),
            "duplicate manifest paths: {duplicates:#?}"
        );
    }

    #[test]
    fn non_wired_entries_have_an_owner_and_a_reason() {
        for entry in WIRING_MANIFEST {
            if entry.status != WiringStatus::Wired {
                assert!(!entry.owner.is_empty(), "{} must name an owner", entry.path);
                assert!(
                    !entry.reason.is_empty(),
                    "{} must give a reason",
                    entry.path
                );
            }
        }
    }

    #[test]
    fn wired_entries_carry_no_diagnostic_behavior() {
        for entry in WIRING_MANIFEST {
            if entry.status == WiringStatus::Wired {
                assert_eq!(
                    entry.behavior,
                    WiringBehavior::None,
                    "{} is Wired but declares a non-None behavior",
                    entry.path
                );
            }
        }
    }

    #[test]
    fn rejected_status_always_pairs_with_rejected_behavior() {
        for entry in WIRING_MANIFEST {
            if entry.status == WiringStatus::Rejected {
                assert_eq!(entry.behavior, WiringBehavior::Rejected, "{}", entry.path);
            } else {
                assert_ne!(entry.behavior, WiringBehavior::Rejected, "{}", entry.path);
            }
        }
    }
}
